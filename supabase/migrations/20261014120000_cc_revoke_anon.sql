-- Call centre tables: nobody signed out may touch them; signed-in users keep only the row-level
-- operations their RLS policies allow (no TRUNCATE / TRIGGER / REFERENCES).
do $$
declare t text;
begin
  for t in select c.relname from pg_class c join pg_namespace n on n.oid = c.relnamespace
           where n.nspname = 'public' and c.relkind = 'r' and c.relname like 'cc\_%'
  loop
    execute format('revoke all on public.%I from anon', t);
    execute format('revoke truncate, trigger, references on public.%I from authenticated', t);
  end loop;
end $$;
