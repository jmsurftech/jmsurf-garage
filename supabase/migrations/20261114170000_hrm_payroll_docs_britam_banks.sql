-- HRM payroll: stored payroll documents, NSSF Tier II to a private scheme, Kenyan bank and branch codes.
-- Re-runnable.
--
-- 1. Stored payroll documents. Each approved run's payslips (and each year's P9) are kept as files in
--    the private bucket payroll-docs at <tenant>/<kind>/<period>/<employee>.html, one row each in
--    hr_payroll_documents, and every email / SMS / WhatsApp / My Space download is logged in
--    hr_payroll_document_deliveries. HR with "See salaries and bank details" manage them; an employee
--    reads only their own (hr_employees.user_id = auth.uid()).
-- 2. NSSF contracted out. hr_employees.nssf_contracted_out + nssf_tier2_scheme (e.g. Britam) +
--    nssf_tier2_scheme_pct: that share of Tier II (employee and employer alike) goes to the private
--    scheme instead of NSSF. The deduction and tax do not change. Each payslip line keeps the amounts in
--    data (nssf_scheme, employer_nssf_scheme, nssf_scheme_name). The salary journal now credits that
--    part to "Pension scheme payable" instead of NSSF payable; debits are unchanged, so it still balances.
-- 3. Kenyan bank and branch codes (Kenya Bankers Association clearing list): kenya_banks and
--    kenya_bank_branches, read by everyone signed in. hr_employees.bank_code / branch_code hold the
--    codes beside bank_name / bank_branch and go into the bank payment file. Existing staff get their
--    codes filled from the names where they match.

-- ── 1. employee columns ─────────────────────────────────────────────────────
alter table public.hr_employees
  add column if not exists bank_code text,
  add column if not exists branch_code text,
  add column if not exists nssf_contracted_out boolean not null default false,
  add column if not exists nssf_tier2_scheme text,
  add column if not exists nssf_tier2_scheme_pct numeric not null default 100;
do $$ begin
  alter table public.hr_employees add constraint hr_employees_nssf_scheme_pct_chk check (nssf_tier2_scheme_pct >= 0 and nssf_tier2_scheme_pct <= 100);
exception when duplicate_object then null; end $$;

-- ── 2. stored payroll documents ─────────────────────────────────────────────
create table if not exists public.hr_payroll_documents (
  id uuid primary key default gen_random_uuid(),
  tenant_id uuid not null references public.tenants(id) on delete cascade,
  run_id uuid references public.hr_payroll_runs(id) on delete set null,
  employee_id uuid not null references public.hr_employees(id) on delete cascade,
  kind text not null check (kind in ('payslip', 'p9')),
  year int not null,
  period text not null,
  path text not null,
  file_name text,
  content_type text not null default 'text/html',
  size_bytes int,
  created_by uuid default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (tenant_id, employee_id, kind, period)
);
create index if not exists hr_payroll_documents_run_idx on public.hr_payroll_documents (run_id);
create index if not exists hr_payroll_documents_emp_idx on public.hr_payroll_documents (employee_id, kind, period desc);

create table if not exists public.hr_payroll_document_deliveries (
  id uuid primary key default gen_random_uuid(),
  tenant_id uuid not null references public.tenants(id) on delete cascade,
  document_id uuid not null references public.hr_payroll_documents(id) on delete cascade,
  channel text not null check (channel in ('email', 'sms', 'whatsapp', 'portal')),
  sent_to text,
  status text not null default 'sent' check (status in ('sent', 'failed')),
  error text,
  sent_by uuid default auth.uid(),
  sent_at timestamptz not null default now()
);
create index if not exists hr_payroll_document_deliveries_doc_idx on public.hr_payroll_document_deliveries (document_id, sent_at desc);

alter table public.hr_payroll_documents enable row level security;
alter table public.hr_payroll_document_deliveries enable row level security;

drop policy if exists hr_payroll_documents_rw on public.hr_payroll_documents;
