-- The bank code for a bank name as people type it ("Equity", "Kenya Commercial Bank", "stanbic").
create or replace function public.kenya_bank_code_for(p_name text) returns text
language sql stable set search_path = public as $$
  select coalesce(
    (select b.code from public.kenya_banks b where lower(b.name) = lower(btrim(coalesce(p_name, ''))) limit 1),
    (select b.code from public.kenya_banks b, unnest(b.match_words) w
      where lower(coalesce(p_name, '')) like '%' || w || '%' order by length(w) desc limit 1))
$$;

-- Branch names compared without case, punctuation or the word "branch".
create or replace function public.kenya_branch_key(p_s text) returns text
language sql immutable as $$
  select regexp_replace(regexp_replace(lower(coalesce(p_s, '')), '\mbranch\M', '', 'g'), '[^a-z0-9]', '', 'g')
$$;

-- The 3-digit branch code for a bank code and branch name: the same name (open branches first),
-- else the one open branch whose name starts with it.
create or replace function public.kenya_branch_code_for(p_bank_code text, p_branch text) returns text
language sql stable set search_path = public as $$
  with k as (select public.kenya_branch_key(p_branch) as key),
  exact as (
    select br.branch_code from public.kenya_bank_branches br, k
     where br.bank_code = p_bank_code and k.key <> '' and public.kenya_branch_key(br.name) = k.key
     order by br.open desc, br.branch_code limit 1),
  starts as (
    select min(br.branch_code) as code, count(*) as n from public.kenya_bank_branches br, k
     where br.bank_code = p_bank_code and br.open and length(k.key) >= 4 and public.kenya_branch_key(br.name) like k.key || '%')
  select coalesce((select branch_code from exact), (select code from starts where n = 1))
$$;
grant execute on function public.kenya_bank_code_for(text), public.kenya_branch_key(text), public.kenya_branch_code_for(text, text) to authenticated;

-- Staff with a bank name but no codes yet: fill them from the names where they match.
update public.hr_employees e set bank_code = public.kenya_bank_code_for(e.bank_name)
 where coalesce(e.bank_code, '') = '' and coalesce(e.bank_name, '') <> '' and public.kenya_bank_code_for(e.bank_name) is not null;
update public.hr_employees e set branch_code = public.kenya_branch_code_for(e.bank_code, e.bank_branch)
 where coalesce(e.branch_code, '') = '' and coalesce(e.bank_code, '') <> '' and coalesce(e.bank_branch, '') <> ''
   and public.kenya_branch_code_for(e.bank_code, e.bank_branch) is not null;
